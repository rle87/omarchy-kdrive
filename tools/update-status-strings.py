#!/usr/bin/env python3
"""Regenerate StatusStrings.js from the upstream kDrive sources.

The widget reads the sync state from the tooltip of the official kDrive tray
icon. That tooltip is built in upstream src/gui/clientgui.cpp from translated
strings, so this script:

  1. checks that clientgui.cpp still builds the tooltip from the strings we
     know (otherwise the widget would silently stop understanding it);
  2. collects every translation of those strings from upstream/translations;
  3. reports which GUI <-> server channel Linux builds use, so we notice when
     kDrive 4 switches Linux to the new comm server.

Usage: tools/update-status-strings.py [--upstream DIR] [--output FILE] [--report FILE]
Exit code 1 when an expected upstream string disappeared.
"""
import argparse
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Widget state -> upstream source strings (as passed to tr() in clientgui.cpp).
STATES = {
    "running": ["Sync is running."],
    "ok": ["Last Sync was successful."],
    "conflicts": ["Sync was successful, unresolved conflicts."],
    "starting": ["Waiting to start syncing."],
    "stopped": ["User Abort."],
    "paused": ["Sync is paused.", "Synchronization is paused"],
    "signin": ["Please sign in"],
    "nofolder": ["There are no sync folders configured."],
    "undefined": ["Undefined State."],
}
FOLDER_FORMAT = "Folder %1: %2"
PAUSED_SUFFIX = "%1 (Sync is paused)"


def upstream_version(upstream: Path) -> str:
    try:
        out = subprocess.run(["git", "-C", str(upstream), "describe", "--tags", "--always"],
                             capture_output=True, text=True, check=True).stdout.strip()
        if out:
            return out
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass
    text = (upstream / "VERSION.cmake").read_text()
    parts = [re.search(rf"KDRIVE_VERSION_{p}\s+(\d+)", text) for p in ("MAJOR", "MINOR", "PATCH")]
    return ".".join(m.group(1) for m in parts if m)


def check_sources(upstream: Path) -> list[str]:
    source = (upstream / "src/gui/clientgui.cpp").read_text()
    wanted = [s for strings in STATES.values() for s in strings] + [FOLDER_FORMAT, PAUSED_SUFFIX]
    return [s for s in wanted if f'tr("{s}")' not in source]


def linux_comm_channel(upstream: Path) -> str:
    header = (upstream / "src/server/appserver.h").read_text()
    match = re.search(r"static bool useOldCommServer\(\)\s*\{(.*?)\n\s*\}\n", header, re.S)
    if not match:
        return "unknown"
    body = match.group(1)
    # Linux takes the #else branch when there is one, otherwise the whole body.
    linux = body.split("#else", 1)[1].split("#endif", 1)[0] if "#else" in body else body
    return "old" if re.search(r"return\s+true\s*;", linux) else "new"


def collect_translations(upstream: Path) -> dict[str, set[str]]:
    sources = {s for strings in STATES.values() for s in strings} | {FOLDER_FORMAT, PAUSED_SUFFIX}
    found = {s: {s} for s in sources}
    for ts in sorted((upstream / "translations").glob("client_*.ts")):
        for message in ET.parse(ts).getroot().iter("message"):
            src = message.findtext("source")
            if src not in sources:
                continue
            tr = message.find("translation")
            if tr is None or tr.get("type") in ("unfinished", "obsolete") or not (tr.text or "").strip():
                continue
            found[src].add(tr.text)
    return found


def render(version: str, channel: str, found: dict[str, set[str]]) -> str:
    states = {state: sorted({t for s in strings for t in found[s]}) for state, strings in STATES.items()}
    dump = lambda value: json.dumps(value, ensure_ascii=False, indent=2)
    return (
        ".pragma library\n\n"
        "// Generated by tools/update-status-strings.py from the upstream kDrive sources.\n"
        "// Do not edit by hand: run the script after updating the upstream submodule.\n\n"
        f"var upstreamVersion = {json.dumps(version)}\n"
        f"var linuxCommChannel = {json.dumps(channel)}\n\n"
        f"var folderFormats = {dump(sorted(found[FOLDER_FORMAT]))}\n\n"
        f"var pausedSuffixes = {dump(sorted(found[PAUSED_SUFFIX]))}\n\n"
        f"var states = {dump(states)}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--upstream", type=Path, default=ROOT / "upstream")
    parser.add_argument("--output", type=Path, default=ROOT / "StatusStrings.js")
    parser.add_argument("--report", type=Path, help="write a Markdown report here")
    args = parser.parse_args()

    version = upstream_version(args.upstream)
    missing = check_sources(args.upstream)
    channel = linux_comm_channel(args.upstream)
    found = collect_translations(args.upstream)
    args.output.write_text(render(version, channel, found))

    report = [f"## kDrive upstream {version}", ""]
    report.append(f"- Translations: {sum(len(v) for v in found.values())} strings collected.")
    if channel == "old":
        report.append("- Linux GUI channel: old comm server (single connection), tray tooltip stays the only safe source.")
    else:
        report.append(f"- **Linux GUI channel: {channel}.** The new comm server may now allow a direct, "
                      "multi-client connection: time to look at pause/resume support.")
    if missing:
        report.append("- **Tray tooltip strings missing from clientgui.cpp:** " + ", ".join(f"`{m}`" for m in missing))
        report.append("  The widget may no longer understand the kDrive status; check `ClientGui::computeOverallSyncStatus`.")
    else:
        report.append("- Tray tooltip strings: all still present in clientgui.cpp.")
    text = "\n".join(report) + "\n"
    print(text)
    if args.report:
        args.report.write_text(text)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
